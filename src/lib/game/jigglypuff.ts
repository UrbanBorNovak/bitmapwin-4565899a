/** Map span: BITMAP heights 0 … MAP_SPAN-1. */
const MAP_SPAN = 840_000;
// Multiplier coprime with MAP_SPAN → pool index → unique BITMAP (a fixed permutation).
const MULT = 331_447;
const OFFSET = 118_813;

export type Jigglypuff = { index: number; inscriptionId: string; bitmap: number };

/** Deterministic, unique BITMAP where pool item #index is found. */
export function jigglypuffBitmap(index: number): number {
  return (index * MULT + OFFSET) % MAP_SPAN;
}

export type JigglypuffSet = { list: Jigglypuff[]; byBitmap: Map<number, Jigglypuff> };

let cached: JigglypuffSet | null = null;

/** Synchronous — the pool is hardcoded, nothing to load. */
export function useJigglypuff(): JigglypuffSet {
  if (!cached) {
    const list = JIGGLYPUFF_IDS.map((inscriptionId, index) => ({
      index,
      inscriptionId,
      bitmap: jigglypuffBitmap(index),
    }));
    cached = { list, byBitmap: new Map(list.map((j) => [j.bitmap, j])) };
  }
  return cached;
}
